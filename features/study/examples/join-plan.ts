/**
 * 채운 단어를 **언제** 학습에 붙이는가 — 순수 함수.
 *
 * 스펙 §6 은 세 갈래를 놓고 「시트가 닫힐 때 한 번에 합류」를 골랐는데, 바로 아래 ⚠️ 는
 * 「현재 배치는 건드리지 않는다 — 합류는 다음 배치부터」라고 적었다. **두 말이었고 구현은
 * 아래쪽을 따랐다.** 그래서 채우기가 끝나도 진도는 묶음이 끝날 때까지 5 그대로였다.
 *
 * 🔴 **그 침묵을 만든 사람이 직접 오해했다**(2026-09-03 iOS 실기). 3개를 채우고 「다 채웠어요」
 * 까지 본 뒤 화면을 보고 「다 채워졌는데 문항은 5개야」라고 읽었다. 설계대로 도는데 쓰는
 * 사람에게는 **안 된 것으로 보인다** — 누른 버튼이 약속한 것은 «지금 학습하기»였다.
 *
 * 그래서 「전체」에서는 채우기가 끝나는 즉시 붙인다. 진도가 3/5 → **3/8** 로 한 번에 오른다.
 *
 * 🔑 **원래 이 동작을 택한 근거는 여기 해당하지 않는다.** §6 이 1안을 버린 이유는 «학습
 * 도중 총 문항이 슬금슬금 는다»였는데, 그것은 **채우는 도중 하나씩** 붙일 때의 이야기다.
 * 다 끝난 뒤 한 번에 올리는 것은 슬금슬금이 아니라 한 번의 갱신이고, 그 순간 화면에는
 * 「N개를 다 채웠어요」가 함께 떠 있어 숫자가 왜 변했는지가 설명된다.
 *
 * 🔴 **숫자로 정한 묶음은 그대로 둔다.** 5개씩 끊어 달라고 한 사람에게 3/8 을 보이면
 * 거짓말이다 — 이번 묶음은 여전히 5문항이고 6~8번은 다음 묶음이다. 그 경계는 사용자가
 * 원해서 만든 것이라 채우기가 지울 수 없다(batchSizeNum 주석의 같은 규칙).
 */

export interface JoinNowInput {
  /** 학습 설정의 묶음 크기. `'all'` = 「전체」(경계가 없다). */
  batchSize: 'all' | number;
  /** 채우기가 아직 도는 중인가 — 도는 동안은 붙이지 않는다(슬금슬금 방지). */
  filling: boolean;
  /** 지금 학습에 들어 있는 문항 수. 0 이면 아직 세션이 안 열린 상태다. */
  studyCount: number;
  /** 붙일 수 있는 단어 수 — 채워져서 이제 출제할 수 있게 된 것. */
  joinableCount: number;
}

/**
 * 묶음이 끝나기를 기다리지 않고 **지금** 붙일 것인가.
 *
 * false 를 돌려줘도 합류가 사라지는 것은 아니다 — 묶음이 끝나는 자리의 `flushJoin` 이
 * 그대로 받는다. 이 함수가 정하는 것은 **시점 하나**뿐이다.
 */
export function shouldJoinNow(s: JoinNowInput): boolean {
  // 붙일 것이 없으면 볼 것도 없다.
  if (s.joinableCount === 0) return false;
  // 도는 중에 붙이면 문항이 하나씩 늘어난다 — §6 이 버린 1안이 그것이다.
  if (s.filling) return false;
  // 🔴 아직 출제할 것이 하나도 없는 상태(B)는 **첫 개방**이 맡는다. 여기서 같이 붙이면
  //    두 곳이 같은 일을 하게 되고, 그 화면은 「채워야 시작된다」라 규칙도 다르다.
  if (s.studyCount === 0) return false;
  // 숫자로 정한 경계는 사용자의 것이다.
  return s.batchSize === 'all';
}
