// 용언 활용 판정 회귀 테스트.
//
// 케이스는 전부 실제 사례다 — 2026-08-28 사다리 4덱 3,168장을 이 판정기로 세면서
// 나온 정답·오답이고, 맨 앞 `그러다`가 레딧 제보자가 발견해 이 작업을 시작하게 한
// 바로 그 카드다. 판정기의 목적은 완벽한 형태소 분석이 아니라 사람이 볼 후보를
// 좁히는 것이므로, 잡아야 할 것과 통과시켜야 할 것을 함께 본다.
import { termUsedInExample, verbUsedInExample, stemOf, looksLikeVerb } from '@/scripts/lib/ko-conjugation';

describe('예문이 표제어를 안 쓴 것을 잡는다', () => {
  // 🔴 이것이 전부의 출발점이다. 옛 검사는 용언을 한 글자로 완화해서 봤고,
  //    "그"가 "그가 그렇게"에 걸려 이 카드를 통과시켰다.
  test('그러다 — 예문은 그렇다(그렇게)를 썼다', () => {
    expect(verbUsedInExample('그러다', '그가 그렇게 갑자기 태도를 바꿀 줄은 아무도 예상하지 못했다.')).toBe(false);
  });

  test.each([
    ['뛰어나다', '그는 타고난 재능 덕분에 동료들 사이에서 단연 돋보이는 실력을 발휘하고 있다.'],  // 유의어 대체
    ['들이다', '전문가들은 이 새로운 기술을 도입함으로써 생산성을 획기적으로 높일 수 있다.'],      // 무관한 예문
    ['새롭다', '신기술 도입은 기업의 경쟁력을 강화하는 데 필수적인 요소가 될 것이다.'],
    ['비하다', '최신 연구 결과는 이전의 통계와 비교했을 때 상당한 차이를 보여주고 있습니다.'],
    ['올리다', '그는 자신의 연구 논문을 저명한 학술지에 성공적으로 게재하여 주목을 받았습니다.'],
    ['불과하다', '그는 단지 몇 년간의 경험만을 가지고 있을 뿐인데, 벌써부터 책임을 맡기에는 이르다.'],
    ['희다', '눈이 많이 와서 산이 온통 하얗게 변했어요.'],
  ])('%s — 예문에 표제어가 없다', (term, ex) => {
    expect(verbUsedInExample(term, ex)).toBe(false);
  });

  // 명사·부사는 형태가 안 변하므로 그대로 찾는다.
  test.each([
    ['성장', '급격한 사회 변화 속에서 개인의 정서적 성숙을 이루는 것은 쉽지 않은 과제이다.'],
    ['골', '그의 연설은 핵심을 꿰뚫는 통찰력으로 청중에게 깊은 인상을 남겼다.'],
    ['문화재', '정부는 국보 1호인 숭례문 복원을 위해 다각적인 노력을 기울였다.'],
    ['이어', '그는 여러 차례의 실패에도 불구하고 끊임없이 도전하였고, 마침내 꿈을 이루었다.'],
  ])('%s — 용언이 아닌 표제어도 잡는다', (term, ex) => {
    expect(termUsedInExample(term, ex)).toBe(false);
  });
});

describe('정상 활용에 거짓경보를 내지 않는다', () => {
  test.each([
    ['외치다', '시위대는 불만을 거리로 뛰쳐나와 외쳤다.'],        // 이+어 → 여
    ['제외하다', '신입 사원들을 제외한 모든 직원이 참여한다.'],    // 하 + ㄴ
    ['제외하다', '그 항목은 대상에서 제외했다.'],                 // 여불규칙 하 → 해
    ['주어지다', '재능이 이미 충분히 주어져 있었다.'],
    ['빛나다', '그는 무대 위에서 빛났다.'],
    ['무너지다', '압박을 이기지 못하고 결국 무너졌다.'],
    ['애쓰다', '문제를 해결하기 위해 밤낮으로 애썼다.'],
    ['달리다', '버스를 놓칠까 봐 정류장까지 열심히 달렸어요.'],
    ['다치다', '축구를 하다가 넘어져서 무릎을 다쳤어요.'],
  ])('규칙 활용: %s', (term, ex) => {
    expect(verbUsedInExample(term, ex)).toBe(true);
  });

  // 불규칙 활용 — 어간 자체가 바뀌므로 여기서 거짓경보가 가장 많이 난다.
  test.each([
    ['맵다', '이 김치는 정말 매워요.'],           // ㅂ불규칙
    ['돕다', '친구를 도와주었다.'],               // ㅂ불규칙(ㅗ)
    ['듣다', '음악을 들었어요.'],                 // ㄷ불규칙
    ['낫다', '감기가 다 나았어요.'],              // ㅅ불규칙
    ['살다', '시골에 사니까 공기가 좋아요.'],      // ㄹ탈락
    ['쓰다', '편지를 썼어요.'],                   // 으탈락
    ['크다', '키가 많이 컸어요.'],                // 으탈락
    ['자르다', '머리를 짧게 잘랐어요.'],           // 르불규칙
    ['저지르다', '돌이킬 수 없는 실수를 저질렀다.'], // 르불규칙
    ['올바르다', '올바른 판단력은 필수적이다.'],
    ['그렇다', '그가 그렇게 말했다.'],             // ㅎ불규칙 — 위 '그러다'와 짝
    ['파랗다', '가을 하늘이 높고 파래서 좋아요.'],  // ㅎ불규칙 ㅏ→ㅐ
    ['하얗다', '눈이 와서 온 세상이 하얘요.'],      // ㅎ불규칙 ㅑ→ㅒ
    ['빨갛다', '부끄러워서 얼굴이 빨개졌다.'],
    ['하다', '숙제를 열심히 했어요.'],             // 여불규칙, 1음절 어간
    ['되다', '일이 잘 됐어요.'],
    ['계시다', '할머니는 집에 계세요.'],           // 존칭 축약 시→세
  ])('불규칙 활용: %s', (term, ex) => {
    expect(verbUsedInExample(term, ex)).toBe(true);
  });
});

describe('보조 함수', () => {
  test('stemOf 는 -다를 뗀다', () => {
    expect(stemOf('그러다')).toBe('그러');
    expect(stemOf('하다')).toBe('하');
    expect(stemOf('성장')).toBe('성장');
  });

  test('looksLikeVerb 는 -다로 끝나는 것만 용언으로 본다', () => {
    expect(looksLikeVerb('그러다')).toBe(true);
    expect(looksLikeVerb('문화재')).toBe(false);
    expect(looksLikeVerb('다')).toBe(false);   // 한 글자는 어간이 없다
  });

  test('termUsedInExample 은 용언 여부에 따라 갈라 본다', () => {
    expect(termUsedInExample('맵다', '김치가 매워요.')).toBe(true);
    expect(termUsedInExample('김치', '김치가 매워요.')).toBe(true);
    expect(termUsedInExample('김치', '깍두기가 매워요.')).toBe(false);
  });
});

describe('합성 용언이 조사를 끼워 분리된 것은 통과시킨다', () => {
  // 새 검사를 전 덱에 돌리자 이 유형이 오탐으로 무더기로 걸렸다 — 전부 정상 표현이다.
  test.each([
    ['낯가리다', '우리 아기는 낯을 가려서 처음 보는 사람한테는 잘 안 웃어.'],
    ['정들다', '이 동네에 10년 넘게 살았더니 정이 많이 들었어.'],
    ['준비하다', '시험 준비를 열심히 하고 있어요.'],
    ['생각나다', '오랜만에 친구 목소리를 들으니 옛날 생각이 났어요.'],
    ['맛보다', '수많은 시행착오 끝에 비로소 성공의 맛을 볼 수 있었다.'],
  ])('%s', (term, ex) => {
    expect(termUsedInExample(term, ex)).toBe(true);
  });

  // 🔴 완화해도 이것만은 계속 걸려야 한다.
  test('그러다는 분리 매칭을 열어도 여전히 걸린다', () => {
    expect(termUsedInExample('그러다', '그가 그렇게 갑자기 태도를 바꿀 줄은 아무도 예상하지 못했다.')).toBe(false);
  });
  test('뛰어나다도 계속 걸린다', () => {
    expect(termUsedInExample('뛰어나다', '그는 동료들 사이에서 단연 돋보이는 실력을 발휘하고 있다.')).toBe(false);
  });
});

describe('여러 어절짜리 표제어', () => {
  test('어절이 예문에서 흩어져 있어도 통과한다', () => {
    expect(termUsedInExample('몸을 풀다', '경기 전에 몸을 충분히 풀어야 부상을 막을 수 있어요.')).toBe(true);
  });

  test('어절 하나가 빠지면 걸린다', () => {
    expect(termUsedInExample('푹 쉬세요', '약 잘 챙겨 드세요.')).toBe(false);
  });

  // ⚠️ 알려진 한계 — 표제어 자체가 활용형이면(`쉬세요`) 예문의 다른 활용형(`쉬시고`)과
  //    이어지지 않아 걸린다. 어미를 벗겨 내는 완화를 넣으면 잡히지만, 그렇게 느슨해진
  //    판정이 애초에 `그러다`를 놓쳤다. 확인 항목으로 남기는 쪽을 택한다(전 덱에 3건).
  test('표제어가 활용형이면 잡지 못하고 확인 항목으로 남는다', () => {
    expect(termUsedInExample('푹 쉬세요', '푹 쉬시고 약 잘 챙겨 드세요.')).toBe(false);
  });
});

describe('영문 표제어', () => {
  // 슬랭 덱에는 로마자 표제어가 있고, 예문에서는 소문자로 쓰이기도 한다.
  test('대소문자만 다른 것은 통과시킨다', () => {
    expect(termUsedInExample('TMI', '이건 그냥 tmi야.')).toBe(true);
  });

  test('한글 표제어 판정은 그대로다', () => {
    expect(termUsedInExample('그러다', '그가 그렇게 갑자기 태도를 바꿀 줄은 아무도 예상하지 못했다.')).toBe(false);
  });
});
